"""Minimal JSON -> Protobuf converter.

Reads a sample JSON request and response for every RPC, infers the proto3
message definitions from them, and writes one .proto file per service.

Type inference rules (same as most online json-to-proto tools):
    string -> string        true/false -> bool
    integer -> int32/int64  float -> double
    array -> repeated <type of first element>
    object -> nested message (named <Parent><SingularKey>)
"""
import json
from pathlib import Path

PACKAGE = "nobel"

# proto file stem -> (service name, [(rpc, request msg, request json, response msg, response json)])
SERVICES = {
    "category": (
        "CategoryService",
        "Query 1: browse categories and count laureates in one.",
        [
            ("ListCategories", "ListCategoriesRequest", "list_categories_request.json",
             "ListCategoriesResponse", "list_categories_response.json"),
            ("CountLaureates", "CategoryRequest", "category_request.json",
             "CountResponse", "category_response.json"),
        ],
    ),
    "motivation": (
        "MotivationService",
        "Query 2: count laureates whose motivation contains a keyword.",
        [
            ("CountByKeyword", "KeywordRequest", "motivation_request.json",
             "KeywordCountResponse", "motivation_response.json"),
        ],
    ),
    "laureate": (
        "LaureateService",
        "Query 3: find a laureate by first and last name.",
        [
            ("FindLaureate", "LaureateRequest", "laureate_request.json",
             "LaureateResponse", "laureate_response.json"),
        ],
    ),
}


def singular(word):
    if word.endswith("ies"):
        return word[:-3] + "y"
    if word.endswith(("ches", "shes", "sses", "xes")):
        return word[:-2]
    if word.endswith("s"):
        return word[:-1]
    return word


def base_name(msg_name):
    for suffix in ("Request", "Response"):
        if msg_name.endswith(suffix):
            return msg_name[: -len(suffix)]
    return msg_name


def scalar_or_message(key, value, parent, messages):
    if isinstance(value, bool):  # bool before int: bool is a subclass of int
        return "bool"
    if isinstance(value, int):
        return "int32" if -(2**31) <= value < 2**31 else "int64"
    if isinstance(value, float):
        return "double"
    if isinstance(value, str):
        return "string"
    if isinstance(value, dict):
        name = base_name(parent) + singular(key)[:1].upper() + singular(key)[1:]
        build_message(name, value, messages)
        return name
    raise ValueError(f"Cannot infer a proto type for field '{key}': {value!r}")


def infer(key, value, parent, messages):
    if isinstance(value, list):
        if not value:
            raise ValueError(f"Field '{key}' is an empty list; add a sample element")
        return "repeated " + scalar_or_message(key, value[0], parent, messages)
    return scalar_or_message(key, value, parent, messages)


def build_message(name, obj, messages):
    fields = [
        f"  {infer(key, value, name, messages)} {key} = {i};"
        for i, (key, value) in enumerate(obj.items(), 1)
    ]
    body = "\n" + "\n".join(fields) + "\n" if fields else ""
    messages.append(f"message {name} {{{body}}}\n")


def main():
    for stem, (service, comment, rpcs) in SERVICES.items():
        messages = []
        rpc_lines = []
        for rpc, req_name, req_json, resp_name, resp_json in rpcs:
            build_message(req_name, json.loads(Path(req_json).read_text()), messages)
            build_message(resp_name, json.loads(Path(resp_json).read_text()), messages)
            rpc_lines.append(f"  rpc {rpc}({req_name}) returns ({resp_name});")

        text = (
            "// Generated by json2proto.py from the sample JSON request/response files.\n"
            'syntax = "proto3";\n\n'
            f"package {PACKAGE};\n\n"
            f"// {comment}\n"
            f"service {service} {{\n" + "\n".join(rpc_lines) + "\n}\n\n"
            + "\n".join(messages)
        )
        Path(f"{stem}.proto").write_text(text)
        print(f"Wrote {stem}.proto")


if __name__ == "__main__":
    main()
